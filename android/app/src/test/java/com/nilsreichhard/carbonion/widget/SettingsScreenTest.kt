package com.nilsreichhard.carbonion.widget

import android.graphics.Bitmap
import android.graphics.Canvas
import android.graphics.Color
import android.view.View
import android.view.ViewGroup
import android.widget.Spinner
import android.widget.Switch
import android.widget.TextView
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.Robolectric
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode

/** Settings page generated by the watch's config.js/custom.js in QuickJS. */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35], qualifiers = "w400dp-h800dp-hdpi")
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class SettingsScreenTest {
    @Before fun setUp() { assumeTrue("desktop QuickJS library missing", JvmQuickJs.install()) }
    @After fun tearDown() = JvmQuickJs.reset()

    private fun all(v: View): List<View> = if (v is ViewGroup) listOf(v) + (0 until v.childCount).flatMap { all(v.getChildAt(it)) } else listOf(v)

    @Test
    fun rendersClayPageAndGreysThickness() {
        val ctl = Robolectric.buildActivity(SettingsActivity::class.java).setup()
        val act = ctl.get()
        val scroll = act.findViewById<ViewGroup>(android.R.id.content).getChildAt(0) as ViewGroup
        val content = scroll.getChildAt(0)
        val views = all(content)
        val texts = views.filterIsInstance<TextView>().filter { it.isShown }.map { it.text.toString() }
        assertTrue(texts.any { it.contains("Theme") })
        assertTrue(texts.any { it.contains("Background") })
        assertTrue("no selects", views.count { it is Spinner } > 5)
        assertTrue("no toggles", views.count { it is Switch } > 2)
        // Skipped watch-only items stay out.
        assertTrue(texts.none { it.contains("Wrist", true) || it.contains("Backlight", true) })

        val w = (400 * act.resources.displayMetrics.density).toInt()
        content.measure(View.MeasureSpec.makeMeasureSpec(w, View.MeasureSpec.EXACTLY), View.MeasureSpec.makeMeasureSpec(0, View.MeasureSpec.UNSPECIFIED))
        content.layout(0, 0, w, content.measuredHeight)
        val b = Bitmap.createBitmap(w, content.measuredHeight, Bitmap.Config.ARGB_8888)
        val c = Canvas(b); c.drawColor(Color.WHITE); content.draw(c)
        Previews.save(b, "settings-screen")
        assertEquals(w, b.width)
        ctl.pause().stop().destroy()
    }
}
